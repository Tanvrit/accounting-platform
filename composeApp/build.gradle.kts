android {
    namespace = "com.tanvrit.accounting"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.tanvrit.accounting"
        minSdk = 26
        // targetSdk tracks compileSdk (repo convention: they move together).
        targetSdk = 37
        versionCode = appVersionCode
        versionName = appVersionName
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    // Release signing is env-driven and never committed. With no keystore the
    // release AAB is unsigned (fine for scaffold/dry-run), matching the
    // convention in platforms/ai and platforms/wedding.
    signingConfigs {
        create("release") {
            val keystorePath = System.getenv("RELEASE_STORE_FILE")
            if (!keystorePath.isNullOrBlank() && file(keystorePath).exists()) {
                storeFile = file(keystorePath)
                storePassword = System.getenv("RELEASE_STORE_PASSWORD")
                keyAlias = System.getenv("RELEASE_KEY_ALIAS") ?: "tanvrit-accounting-release"
                keyPassword = System.getenv("RELEASE_KEY_PASSWORD")
            } else {
                logger.warn("No release keystore (RELEASE_STORE_FILE unset) — release builds will be unsigned")
            }
        }
    }

    buildTypes {
        getByName("release") {
            isMinifyEnabled = false
            val keystorePath = System.getenv("RELEASE_STORE_FILE")
            if (!keystorePath.isNullOrBlank() && file(keystorePath).exists()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }
}


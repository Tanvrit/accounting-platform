// ─── Build identity ──────────────────────────────────────────────────────────
// The Settings "About" surface reads these generated constants rather than any
// hardcoded version literal, so the displayed version is always the truth.
// Everything the task captures is resolved eagerly at script level (plain
// Strings/File) so it stays configuration-cache safe.
val appVersionName = providers.gradleProperty("VERSION_NAME").getOrElse("1.0.0")
val appVersionCode = providers.gradleProperty("VERSION_CODE").map(String::toInt).getOrElse(1)
val sdkVersionForIdentity = providers.gradleProperty("TANVRIT_SDK_VERSION").getOrElse("unknown")
val buildIdentityOutDir = File(layout.buildDirectory.asFile.get(), "generated/identity")

val generateBuildIdentity =
    tasks.register("generateBuildIdentity") {
        // Configuration-cache safe: copy script-level values into task-locals
        // before doLast so the action captures plain Strings/File, not the
        // script object.
        val ver = appVersionName
        val code = appVersionCode
        val sdk = sdkVersionForIdentity
        val outDir = buildIdentityOutDir
        inputs.property("ver", ver)
        inputs.property("code", code)
        inputs.property("sdk", sdk)
        outputs.dir(outDir)
        doLast {
            val f = File(outDir, "com/tanvrit/accounting/BuildIdentity.kt")
            f.parentFile.mkdirs()
            f.writeText(
                "package com.tanvrit.accounting\n\n" +
                    "// GENERATED by :composeApp:generateBuildIdentity — do not edit.\n" +
                    "internal object BuildIdentity {\n" +
                    "    const val VERSION_NAME: String = \"$ver\"\n" +
                    "    const val VERSION_CODE: Int = $code\n" +
                    "    const val SDK_VERSION: String = \"$sdk\"\n" +
                    "}\n",
            )
        }
    }

